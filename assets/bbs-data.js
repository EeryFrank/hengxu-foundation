function _esc(s){ return s.replace(/</g,'&lt;'); }
function genBoard(boardId, def){
  const out = [];
  for(let i=0;i<def.count;i++){
    const title = def.pre ? def.pre()+def.subj() : (def.tag ? `【${def.tag()}】${def.subj()}` : def.subj());
    const parts = def.body();
    const body = Array.isArray(parts) ? parts.join('\n\n') : parts;
    const t = { id:'g_'+boardId+'_'+i, title, author:def.au(), lv:def.lv(), time:rt(), body:def.tag||def.pre ? body : body };
    // 公告与研讨、封存区帖子允许含标记（vault body 已含 span，不转义）；其余转义
    if(boardId!=='vault') t.body = _esc(t.body);
    if(def.rep && _R()<0.6){
      const n = ri(1,3); t.replies = [];
      let base = new Date(t.time.replace(' ','T')).getTime();
      for(let k=0;k<n;k++){
        const rp = pk(def.rep());
        base += ri(1,26)*3600*1000;
        const d = new Date(base), p = x => String(x).padStart(2,'0');
        t.replies.push({ author:rp.au(), lv:pk(['L1','L2','L3']),
          time:`${d.getFullYear()}-${p(d.getMonth()+1)}-${p(d.getDate())} ${p(d.getHours())}:${p(d.getMinutes())}`,
          body:_esc(rp.b) });
      }
    }
    out.push(t);
  }
  return out;
}

